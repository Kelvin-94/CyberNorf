import { createHash, randomBytes } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, open, rm, stat } from 'node:fs/promises';
import { join, resolve, sep } from 'node:path';
import { Readable, Transform } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { MAX_EVIDENCE_BYTES, isAllowedEvidenceType } from '@/server/domain/quotas';
import { AppError, badRequest, internalError } from '@/server/errors';

/**
 * Storage for uploaded evidence artifacts.
 *
 * The property an auditor needs is not "the file is on disk" but "the file has
 * not changed since we received it". So the hash is computed *while the bytes are
 * written*, never afterwards from a re-read, and it is stored with the record. A
 * later verification re-reads the file and compares. Anything that mutates the
 * file after upload — a bad restore, a truncation, a curious operator — shows up
 * as MISMATCH rather than silently changing the evidence.
 *
 * Layout: `<EVIDENCE_DIR>/<shard>/<blobKey>` with the blob key generated here from
 * a random token. The key is never derived from the uploaded file name, the
 * content type, or anything else a client controls, which removes path traversal
 * as a class of bug rather than requiring careful sanitising. The database CHECK
 * constraint enforces the same shape, so a future code path cannot loosen it.
 *
 * The shard is the first byte of the key. One directory with tens of thousands of
 * entries is slow to list on many filesystems; two levels keep it bounded.
 */

/** 32 lowercase hex characters, i.e. 128 bits of randomness. */
const BLOB_KEY_PATTERN = /^[a-z0-9]{20,40}$/;

export class EvidenceStorageUnavailableError extends AppError {
  constructor() {
    super(
      503,
      'INTERNAL_ERROR',
      'Evidence storage is not configured on this deployment, so file attachments are unavailable.',
    );
  }
}

/** The configured root, or null when uploading is disabled. */
export function evidenceRoot(): string | null {
  const configured = process.env.EVIDENCE_DIR?.trim();
  return configured ? resolve(configured) : null;
}

export function generateBlobKey(): string {
  // hex, not base64url: no `-` or `_`, which keeps the key safe to use as a
  // directory entry on every filesystem and easy to match against the constraint.
  return randomBytes(16).toString('hex');
}

/**
 * Maps a blob key to its absolute path, refusing anything that could escape the
 * root. The key is generated by us, so this is defence in depth: it makes a
 * corrupted database row or a hand-written INSERT a loud failure instead of an
 * arbitrary file read.
 */
export function blobPath(root: string, blobKey: string): string {
  if (!BLOB_KEY_PATTERN.test(blobKey)) {
    throw internalError();
  }
  const shard = blobKey.slice(0, 2);
  const full = join(root, shard, blobKey);
  // resolve() collapses `..`; the prefix check then proves the result is inside
  // the root. `sep` is appended so a sibling directory with the root as a prefix
  // (`/data/evidence-other`) cannot pass.
  const normalisedRoot = resolve(root);
  if (!full.startsWith(`${normalisedRoot}${sep}`)) {
    throw internalError();
  }
  return full;
}

export interface StoredArtifact {
  blobKey: string;
  sizeBytes: number;
  sha256: string;
}

/**
 * Streams a request body to disk while hashing it.
 *
 * A single pass, for two reasons: the body may only be readable once, and hashing
 * a 10 MB artifact twice is wasted I/O. The size limit is enforced inside the
 * stream, so an oversized upload stops at the limit rather than filling the disk
 * and being rejected afterwards. A partial file is removed on any failure, so a
 * crashed upload cannot leave an orphan that looks like evidence.
 */
export async function storeArtifact(input: {
  root: string;
  declaredContentType: string;
  body: ReadableStream<Uint8Array>;
  maxBytes?: number;
}): Promise<StoredArtifact> {
  const maxBytes = input.maxBytes ?? MAX_EVIDENCE_BYTES;
  if (!isAllowedEvidenceType(input.declaredContentType)) {
    throw badRequest(
      'That file type is not accepted for evidence. Use PDF, PNG, JPEG, WebP, plain text, CSV, JSON or Markdown.',
    );
  }

  const blobKey = generateBlobKey();
  const target = blobPath(input.root, blobKey);
  await mkdir(join(input.root, blobKey.slice(0, 2)), { recursive: true, mode: 0o750 });

  const hash = createHash('sha256');
  let sizeBytes = 0;

  // The meter sits in the pipeline ahead of the writer, so the size check rejects
  // an oversized upload before the overflowing chunk reaches the disk.
  try {
    const file = await open(target, 'wx', 0o640);
    try {
      const writable = file.createWriteStream();
      const meter = new Transform({
        transform(chunk: Buffer, _encoding, callback) {
          sizeBytes += chunk.byteLength;
          if (sizeBytes > maxBytes) {
            callback(
              new AppError(
                413,
                'PAYLOAD_TOO_LARGE',
                `Evidence files are limited to ${Math.round(maxBytes / (1024 * 1024))} MB.`,
              ),
            );
            return;
          }
          hash.update(chunk);
          callback(null, chunk);
        },
      });
      await pipeline(Readable.fromWeb(input.body as never), meter, writable);
    } finally {
      await file.close();
    }
  } catch (error) {
    // Nothing partially written is ever referenced, and leaving it would leak
    // disk space that no row points at.
    await rm(target, { force: true });
    throw error;
  }

  if (sizeBytes === 0) {
    await rm(target, { force: true });
    throw badRequest('The uploaded file is empty.');
  }

  return { blobKey, sizeBytes, sha256: hash.digest('hex') };
}

export type IntegrityOutcome = 'INTACT' | 'MISMATCH' | 'MISSING';

/**
 * Re-reads a stored artifact and compares it to the recorded hash.
 *
 * Streamed rather than read whole: an evidence bundle can be several megabytes
 * and verification runs over many rows in the sweep, so buffering each one would
 * make the sweep's memory use proportional to the largest file.
 */
export async function verifyArtifact(input: {
  root: string;
  blobKey: string;
  expectedSha256: string;
}): Promise<{ outcome: IntegrityOutcome; actualSha256: string | null; sizeBytes: number | null }> {
  const path = blobPath(input.root, input.blobKey);

  let sizeBytes: number;
  try {
    const info = await stat(path);
    if (!info.isFile()) {
      return { outcome: 'MISSING', actualSha256: null, sizeBytes: null };
    }
    sizeBytes = info.size;
  } catch {
    return { outcome: 'MISSING', actualSha256: null, sizeBytes: null };
  }

  const hash = createHash('sha256');
  try {
    // Consume the file once, hashing each chunk; a stream error means the file
    // could not be read to the end, which is reported as MISSING rather than as
    // a mismatch against a partial hash.
    for await (const chunk of createReadStream(path)) {
      hash.update(chunk as Buffer);
    }
  } catch {
    return { outcome: 'MISSING', actualSha256: null, sizeBytes };
  }

  const actual = hash.digest('hex');
  return {
    outcome: actual === input.expectedSha256 ? 'INTACT' : 'MISMATCH',
    actualSha256: actual,
    sizeBytes,
  };
}

/** Removes one stored artifact. Missing is success: the goal is that it is gone. */
export async function deleteArtifact(root: string, blobKey: string): Promise<void> {
  await rm(blobPath(root, blobKey), { force: true });
}

/**
 * Removes every artifact belonging to an evidence record before the row is
 * deleted, so a deleted control does not leave unreferenced files behind.
 */
export async function deleteArtifacts(
  root: string,
  blobKeys: readonly string[],
): Promise<{ removed: number; failed: string[] }> {
  const failed: string[] = [];
  let removed = 0;
  for (const key of blobKeys) {
    try {
      await deleteArtifact(root, key);
      removed += 1;
    } catch {
      // The row is going away regardless; a file that could not be removed is
      // reported so the operator can clean it up, not silently ignored.
      failed.push(key);
    }
  }
  return { removed, failed };
}

/** True when the storage directory exists and is writable by this process. */
export async function probeStorage(root: string): Promise<boolean> {
  const probe = join(root, `.probe-${randomBytes(8).toString('hex')}`);
  try {
    await mkdir(root, { recursive: true, mode: 0o750 });
    const handle = await open(probe, 'w', 0o600);
    await handle.close();
    await rm(probe, { force: true });
    return true;
  } catch {
    return false;
  }
}

/** Human-readable file name for a Content-Disposition header. */
export function sanitiseFileName(value: string): string {
  // Strip directory separators and control characters, then cap the length so a
  // header cannot be broken by a crafted name. The stored name is only metadata;
  // it is never used to build a path.
  const cleaned = value
    // eslint-disable-next-line no-control-regex -- C0 controls and DEL are exactly what must be removed here.
    .replace(/[\u0000-\u001f\u007f]/g, '')
    .replace(/[/\\]/g, '_')
    .trim();
  const base = cleaned.length === 0 ? 'evidence' : cleaned;
  return base.length > 120 ? base.slice(0, 120) : base;
}
